#pragma once

#include <juce_gui_basics/juce_gui_basics.h>

namespace SuiteUI
{
    /**
        Draws a brand lockup (the FROTH Audio wordmark, the mark and the product name) at the left of area.
        The image keeps its proportions and is reduced to fit the height. The lockup artwork is generated by
        tools/brand/make_brand.py and embedded per plugin with juce_add_binary_data.
    */
    inline void drawBrandLockup (juce::Graphics& g, juce::Rectangle<int> area, const juce::Image& lockup)
    {
        if (! lockup.isValid())
            return;

        g.drawImageWithin (lockup, area.getX(), area.getY(), area.getWidth(), area.getHeight(),
                           juce::RectanglePlacement (juce::RectanglePlacement::xLeft
                                                     | juce::RectanglePlacement::yMid
                                                     | juce::RectanglePlacement::onlyReduceInSize),
                           false);
    }
}  // namespace SuiteUI
